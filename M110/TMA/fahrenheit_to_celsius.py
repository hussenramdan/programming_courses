def fahrenheit_to_celsius(fahrenheit):
    return (fahrenheit - 32) * 5 / 9

fahrenheit_temp = float(input ("Enter a Temperture: "))
celsius_temp = fahrenheit_to_celsius(fahrenheit_temp)
print(f"The Temperture IS {celsius_temp:.2f}")



